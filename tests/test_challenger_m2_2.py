class TestLoggerIntegrationAndShielding:
    """Stress-test Logger integration with environment capture and exception shielding."""

    def test_logger_metadata_environment_and_git_parity(self, temp_git_repo: Path, monkeypatch):
        """Verify meta.json maintains dual parity for both 'environment' and 'git' blocks."""
        monkeypatch.chdir(temp_git_repo)
        logs_dir = temp_git_repo / "logs"

        logger = Logger(run_name="parity_test_run", log_dir=logs_dir, capture_env=True)
        logger.close()

        meta_file = logs_dir / "parity_test_run" / constants.META_FILE
        assert meta_file.exists()
        meta = json.loads(meta_file.read_text(encoding="utf-8"))

        assert "environment" in meta
        assert "git" in meta

        env_block = meta["environment"]
        git_block = meta["git"]

        assert git_block["git_commit"] == env_block["git_commit"]
        assert git_block["git_branch"] == env_block["git_branch"]
        assert git_block["is_dirty"] == env_block["is_dirty"]
        assert git_block["git_dirty"] == env_block["git_dirty"]

    def test_logger_dirty_repo_generates_diff_patch(self, temp_git_repo: Path, monkeypatch):
        """Verify dirty git repo produces non-empty diff.patch alongside meta.json."""
        tracked = temp_git_repo / "initial.txt"
        with open(tracked, "a", encoding="utf-8") as f:
            f.write("modification for diff test\n")

        monkeypatch.chdir(temp_git_repo)
        logs_dir = temp_git_repo / "logs"

        logger = Logger(run_name="dirty_diff_run", log_dir=logs_dir, capture_env=True)
        logger.close()

        diff_file = logs_dir / "dirty_diff_run" / constants.DIFF_FILE
        assert diff_file.exists()
        assert diff_file.stat().st_size > 0

        content = diff_file.read_text(encoding="utf-8")
        assert "initial.txt" in content
        assert "modification for diff test" in content

    def test_logger_clean_repo_omits_diff_patch(self, temp_git_repo: Path, monkeypatch):
        """Verify clean git repo does not generate diff.patch."""
        monkeypatch.chdir(temp_git_repo)
        logs_dir = temp_git_repo / "logs"

        logger = Logger(run_name="clean_diff_run", log_dir=logs_dir, capture_env=True)
        logger.close()

        diff_file = logs_dir / "clean_diff_run" / constants.DIFF_FILE
        assert not diff_file.exists()

    def test_logger_capture_env_false_omits_patch_even_if_dirty(self, temp_git_repo: Path, monkeypatch):
        """Verify capture_env=False suppresses diff.patch generation even on a dirty repo."""
        tracked = temp_git_repo / "initial.txt"
        with open(tracked, "a", encoding="utf-8") as f:
            f.write("ignored dirty change\n")

        monkeypatch.chdir(temp_git_repo)
        logs_dir = temp_git_repo / "logs"

        logger = Logger(run_name="no_env_run", log_dir=logs_dir, capture_env=False)
        logger.close()

        diff_file = logs_dir / "no_env_run" / constants.DIFF_FILE
        assert not diff_file.exists()

        meta_file = logs_dir / "no_env_run" / constants.META_FILE
        meta = json.loads(meta_file.read_text(encoding="utf-8"))
        assert meta["environment"] == {}
        assert meta["git"] == {}

    def test_logger_shielded_against_capture_environment_crash(self, temp_git_repo: Path, monkeypatch):
        """Verify Logger initializes and logs normally even if capture_environment raises an exception."""
        import experiment_logger.env

        def exploding_env():
            raise RuntimeError("Fatal environment inspection fault")

        monkeypatch.setattr(experiment_logger.env, "capture_environment", exploding_env)
        monkeypatch.chdir(temp_git_repo)
        logs_dir = temp_git_repo / "logs"

        logger = Logger(run_name="env_crash_survived", log_dir=logs_dir, capture_env=True)
        logger.log({"step": 1, "accuracy": 0.95})
        logger.close()

        meta_file = logs_dir / "env_crash_survived" / constants.META_FILE
        assert meta_file.exists()
        meta = json.loads(meta_file.read_text(encoding="utf-8"))
        assert "environment" in meta
        # Safe fallback was populated
        assert meta["environment"]["packages"] == {}

        log_file = logs_dir / "env_crash_survived" / constants.LOG_FILE
        assert log_file.exists()

    def test_logger_shielded_against_create_diff_patch_crash(self, temp_git_repo: Path, monkeypatch):
        """Verify Logger initializes normally even if create_diff_patch raises an unhandled exception."""
        import experiment_logger.env

        tracked = temp_git_repo / "initial.txt"
        with open(tracked, "a", encoding="utf-8") as f:
            f.write("dirty change\n")

        def exploding_patch(*args, **kwargs):
            raise OSError("Read-only file system or disk full")

        monkeypatch.setattr(experiment_logger.env, "create_diff_patch", exploding_patch)
        monkeypatch.chdir(temp_git_repo)
        logs_dir = temp_git_repo / "logs"

        logger = Logger(run_name="patch_crash_survived", log_dir=logs_dir, capture_env=True)
        logger.log({"step": 1, "loss": 0.1})
        logger.close()

        meta_file = logs_dir / "patch_crash_survived" / constants.META_FILE
        assert meta_file.exists()

    def test_logger_resumed_run_does_not_clobber_diff_patch(self, temp_git_repo: Path, monkeypatch):
        """Verify resumed run (restart=True) does not overwrite or remove pre-existing diff.patch."""
        monkeypatch.chdir(temp_git_repo)
        logs_dir = temp_git_repo / "logs"

        # 1. Dirty state creates diff.patch
        tracked = temp_git_repo / "initial.txt"
        with open(tracked, "a", encoding="utf-8") as f:
            f.write("first session change\n")

        logger1 = Logger(run_name="resume_patch_run", log_dir=logs_dir, capture_env=True)
        logger1.log({"step": 1, "loss": 0.5})
        logger1.close()

        diff_file = logs_dir / "resume_patch_run" / constants.DIFF_FILE
        assert diff_file.exists()
        initial_patch_bytes = diff_file.read_bytes()

        # 2. Revert repo to clean state
        subprocess.run(["git", "checkout", "initial.txt"], cwd=temp_git_repo, check=True, capture_output=True)

        # 3. Resume run
        logger2 = Logger(run_name="resume_patch_run", log_dir=logs_dir, restart=True)
        logger2.log({"step": 2, "loss": 0.3})
        logger2.close()

        # 4. Existing diff.patch was preserved without overwrite or deletion
        assert diff_file.exists()
        assert diff_file.read_bytes() == initial_patch_bytes
