"""
Milestone 2 Failure Injection & Isolation Stress Test Suite.
Generated by Challenger M2-2 (challenger_m2_2).

Stress Dimensions Covered:
1. Subprocess Failure Injection:
   - FileNotFoundError (missing git executable) in capture_git_info and create_diff_patch
   - TimeoutExpired during tree check, commit SHA query, branch query, and diff generation
   - PermissionError during git invocation and patch file writing
   - Non-zero process exit codes (1, 128, 255) across all subprocess commands
   - Malformed/corrupted command output (non-hex SHA, empty branch name, non-boolean work tree)

2. Package Distribution Corruption:
   - Non-iterable distributions (distributions() returns None, int, or raises)
   - Generator failure mid-iteration
   - Broken distributions where .name / .metadata / .version raise arbitrary exceptions
   - Missing Name or Version attributes (fallbacks to 'unknown' or skip)
   - Distribution with exploding str(name)
   - Mixed corrupted and valid distributions in single inspection pass

3. Logger Lifecycle & Contract Parity:
   - meta.json parity between 'environment' and 'git' sections
   - Automatic generation of diff.patch when working tree is dirty
   - Clean omission of diff.patch when working tree is clean or capture_env=False
   - Complete exception shielding: Logger survives arbitrary failure of capture_environment,
     capture_git_info, or create_diff_patch
   - Resumed runs (restart=True) preserve initial session environment and diff.patch
"""

