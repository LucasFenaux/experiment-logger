        jsonl = tmp_path / "array_metrics.jsonl"
        with open(jsonl, "w", encoding="utf-8") as f:
            f.write(json.dumps({"step": 1, "token_losses": [0.5, 0.4, 0.3, 0.2, 0.1]}) + "\n")
            f.write(json.dumps({"step": 2, "token_losses": [0.45, 0.35, 0.25, 0.15, 0.05]}) + "\n")
