        assert is_extreme_grad.iloc[0]  # +Infinity > 1e9
        assert not is_extreme_grad.iloc[1]

        # Aggregation functions
        assert df["loss"].dropna().mean() == pytest.approx(0.375)
        assert df["nan_metric"].dropna().sum() == pytest.approx(30.0)

