class TestDotNotatedAndNestedHyperparameters:
    """Stress-test literal dots in keys, deep dictionary nesting, and key collisions."""

    def test_literal_dotted_keys(self, tmp_path: Path) -> None:
        """Verify hyperparameters with literal dots in keys are preserved with prefix."""
        run_dir = tmp_path / "literal_dots"
        hp = {
            "model.backbone": "resnet50",
            "model.pretrained": True,
            "train.optimizer.type": "adamw",
            "train.optimizer.lr": 1e-3,
        }
        _create_run(run_dir, run_name="dots", hyperparameters=hp, metrics=[{"step": 1, "loss": 0.5}])

        reader = LogReader()
        df = reader.read_run(run_dir)

        assert df["hyperparameters.model.backbone"].iloc[0] == "resnet50"
        assert df["hyperparameters.model.pretrained"].iloc[0] == True
        assert df["hyperparameters.train.optimizer.type"].iloc[0] == "adamw"
        assert df["hyperparameters.train.optimizer.lr"].iloc[0] == 1e-3

    def test_nested_dictionaries_flattening_and_parent_preservation(self, tmp_path: Path) -> None:
        """Verify nested dicts produce flattened dotted keys AND preserve parent dict object."""
        run_dir = tmp_path / "nested_dict"
        nested_hp = {
            "model": {
                "arch": "transformer",
                "encoder": {
                    "heads": 8,
                    "dim": 512,
                },
            },
            "batch_size": 32,
        }
        _create_run(run_dir, run_name="nested", hyperparameters=nested_hp, metrics=[{"step": 1, "loss": 0.5}])

        reader = LogReader()
        df = reader.read_run(run_dir)

        # Flattened leaf keys
        assert df["hyperparameters.model.arch"].iloc[0] == "transformer"
        assert df["hyperparameters.model.encoder.heads"].iloc[0] == 8
        assert df["hyperparameters.model.encoder.dim"].iloc[0] == 512
        assert df["hyperparameters.batch_size"].iloc[0] == 32

        # Parent dict preservation
        assert "hyperparameters.model" in df.columns
        assert isinstance(df["hyperparameters.model"].iloc[0], dict)
        assert df["hyperparameters.model"].iloc[0]["arch"] == "transformer"

    def test_overlapping_literal_dot_and_nested_dict(self, tmp_path: Path) -> None:
        """Verify co-existence of literal dotted key and nested dictionary."""
        run_dir = tmp_path / "overlapping"
        hp = {
            "model.backbone": "resnet50",
            "model": {
                "layers": 50,
                "variant": "v2",
            },
        }
        _create_run(run_dir, run_name="overlap", hyperparameters=hp, metrics=[{"step": 1, "loss": 0.5}])

        reader = LogReader()
        df = reader.read_run(run_dir)

        assert df["hyperparameters.model.backbone"].iloc[0] == "resnet50"
        assert df["hyperparameters.model.layers"].iloc[0] == 50
        assert df["hyperparameters.model.variant"].iloc[0] == "v2"

    def test_deeply_nested_dict_7_levels(self, tmp_path: Path) -> None:
        """Verify deep 7-level dictionary flattening without recursion errors."""
        run_dir = tmp_path / "deep_nest"
        hp = {"a": {"b": {"c": {"d": {"e": {"f": {"g": "terminus"}}}}}}}
        _create_run(run_dir, run_name="deep_nest", hyperparameters=hp, metrics=[{"step": 1, "loss": 0.1}])

        reader = LogReader()
        df = reader.read_run(run_dir)

        col = "hyperparameters.a.b.c.d.e.f.g"
        assert col in df.columns
        assert df[col].iloc[0] == "terminus"

    def test_empty_nested_dictionary_handling(self, tmp_path: Path) -> None:
        """Verify empty nested dicts don't crash flattening or DataFrame assignment."""
        run_dir = tmp_path / "empty_nested"
        hp = {
            "empty_model": {},
            "regular_param": 42,
            "nested_with_empty": {"empty_child": {}},
        }
        _create_run(run_dir, run_name="empty_nested", hyperparameters=hp, metrics=[{"step": 1, "loss": 0.1}])

        reader = LogReader()
        df = reader.read_run(run_dir)

        assert df["hyperparameters.regular_param"].iloc[0] == 42
        assert df["hyperparameters.empty_model"].iloc[0] == {}
        assert df["hyperparameters.nested_with_empty.empty_child"].iloc[0] == {}

    def test_non_string_keys_in_nested_dict(self, tmp_path: Path) -> None:
        """Verify non-string keys in nested dictionary are safely converted to string keys."""
        run_dir = tmp_path / "int_keys"
        # In Python dict, integer keys are allowed; JSON serialization stringifies them
        hp = {
            "layer_sizes": {"1": 128, "2": 256, "3": 512},
        }
        _create_run(run_dir, run_name="int_keys", hyperparameters=hp, metrics=[{"step": 1, "loss": 0.1}])

        reader = LogReader()
        df = reader.read_run(run_dir)

        assert df["hyperparameters.layer_sizes.1"].iloc[0] == 128
        assert df["hyperparameters.layer_sizes.2"].iloc[0] == 256
        assert df["hyperparameters.layer_sizes.3"].iloc[0] == 512

    def test_nested_dict_containing_special_floats(self, tmp_path: Path) -> None:
        """Verify special float strings inside nested dictionary are deserialized."""
        run_dir = tmp_path / "nested_floats"
        hp = {
            "bounds": {
                "lower": "-Infinity",
                "upper": "+Infinity",
                "invalid": "NaN",
            }
        }
        _create_run(run_dir, run_name="nested_floats", hyperparameters=hp, metrics=[{"step": 1, "loss": 0.1}])

        reader = LogReader()
        df = reader.read_run(run_dir)

        lower_val = df["hyperparameters.bounds.lower"].iloc[0]
        upper_val = df["hyperparameters.bounds.upper"].iloc[0]
        nan_val = df["hyperparameters.bounds.invalid"].iloc[0]

        assert math.isinf(lower_val) and lower_val < 0
        assert math.isinf(upper_val) and upper_val > 0
        assert math.isnan(nan_val)
