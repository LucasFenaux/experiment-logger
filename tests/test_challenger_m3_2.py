def _create_run(
    run_dir: Path,
    run_name: str | None = None,
    hyperparameters: dict[str, Any] | None = None,
    metrics: list[dict[str, Any]] | None = None,
    write_header: bool = True,
    corrupt_log: bool = False,
    corrupt_meta: bool = False,
    omit_meta: bool = False,
) -> Path:
    """Helper to synthesize a test run on disk with configurable properties."""
    run_dir.mkdir(parents=True, exist_ok=True)

    if not omit_meta:
        meta_file = run_dir / constants.META_FILE
        if corrupt_meta:
            meta_file.write_text("NOT VALID JSON {{{{", encoding="utf-8")
        else:
            meta_data: dict[str, Any] = {}
            if run_name is not None:
                meta_data[constants.RUN_NAME_KEY] = run_name
            if hyperparameters is not None:
                meta_data[constants.HYPERPARAMETERS_KEY] = hyperparameters
            meta_file.write_text(json.dumps(meta_data), encoding="utf-8")

    log_file = run_dir / constants.LOG_FILE
    if corrupt_log:
        log_file.write_text("MALFORMED LINE 1\nMALFORMED LINE 2\n", encoding="utf-8")
    else:
        with open(log_file, "w", encoding="utf-8") as f:
            if write_header:
                header = dict(constants.DEFAULT_HEADER)
                if run_name:
                    header[constants.RUN_NAME_KEY] = run_name
                f.write(json.dumps(header) + "\n")
            if metrics:
                for row in metrics:
                    f.write(json.dumps(row) + "\n")

    return run_dir


