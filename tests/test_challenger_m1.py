class TestChallengerTimestampTamperProtection:
    def test_tamper_protection_discards_user_supplied_timestamps(self, tmp_path: Path):
        """Stress: User-supplied _timestamp and _time_since_start are discarded and replaced."""
        t_before = time.time()
        with Logger("stress_tamper_ts", log_dir=tmp_path) as logger:
            logger.log({
                "step": 1,
                "_timestamp": 12345.0,
                "_time_since_start": -999.0,
                "metric": 100,
            })
        t_after = time.time()

        with open(logger.log_file, "r", encoding="utf-8") as f:
            data = json.loads(f.readlines()[1])

        assert data["_timestamp"] != 12345.0
        assert t_before - 0.5 <= data["_timestamp"] <= t_after + 0.5
        assert data["_time_since_start"] != -999.0
        assert data["_time_since_start"] >= 0.0

    def test_input_dictionary_not_mutated(self, tmp_path: Path):
        """Stress: The caller's input dictionary is never mutated."""
        input_dict = {"step": 1, "loss": 0.5}
        with Logger("stress_immutability", log_dir=tmp_path) as logger:
            logger.log(input_dict)

        assert input_dict == {"step": 1, "loss": 0.5}
        assert "_timestamp" not in input_dict
        assert "_time_since_start" not in input_dict
