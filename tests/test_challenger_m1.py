class TestChallengerRestartIntegrity:
    def test_restart_identical_hyperparameters_allows_append(self, tmp_path: Path):
        """Stress: Identical hyperparameters allow append and do not duplicate line 1 header."""
        hp = {"lr": 0.001, "batch_size": 32, "model": "resnet"}
        with Logger("restart_ok", hyperparameters=hp, log_dir=tmp_path) as l1:
            l1.log({"step": 1, "loss": 0.5})

        with Logger("restart_ok", hyperparameters=hp, log_dir=tmp_path, restart=True) as l2:
            assert l2.run_dir == l1.run_dir
            l2.log({"step": 2, "loss": 0.4})

        # Read back log lines
        with open(tmp_path / "restart_ok" / "log.jsonl", "r", encoding="utf-8") as f:
            lines = [json.loads(line) for line in f if line.strip()]

        assert len(lines) == 3
        assert lines[0]["type"] == "header"
        assert lines[1]["step"] == 1
        assert lines[2]["step"] == 2

    def test_restart_slightly_altered_float_hyperparameter_raises_value_error(self, tmp_path: Path):
        """Stress: Altering float hyperparameter (0.001 vs 0.002) triggers immediate ValueError."""
        with Logger("restart_flt_mismatch", hyperparameters={"lr": 0.001}, log_dir=tmp_path) as l1:
            l1.log({"step": 1, "loss": 0.5})

        with pytest.raises(ValueError, match="hyperparameters mismatch"):
            Logger("restart_flt_mismatch", hyperparameters={"lr": 0.002}, log_dir=tmp_path, restart=True)

    def test_restart_added_hyperparameter_raises_value_error(self, tmp_path: Path):
        """Stress: Adding an extra hyperparameter on restart triggers immediate ValueError."""
        with Logger("restart_add_mismatch", hyperparameters={"lr": 0.001}, log_dir=tmp_path) as l1:
            l1.log({"step": 1, "loss": 0.5})

        with pytest.raises(ValueError, match="hyperparameters mismatch"):
            Logger(
                "restart_add_mismatch",
                hyperparameters={"lr": 0.001, "extra": "unexpected"},
                log_dir=tmp_path,
                restart=True,
            )

    def test_restart_omitted_hyperparameter_raises_value_error(self, tmp_path: Path):
        """Stress: Omitting an existing hyperparameter on restart triggers immediate ValueError."""
        with Logger("restart_omit_mismatch", hyperparameters={"lr": 0.001, "bs": 64}, log_dir=tmp_path) as l1:
            l1.log({"step": 1, "loss": 0.5})

        with pytest.raises(ValueError, match="hyperparameters mismatch"):
            Logger("restart_omit_mismatch", hyperparameters={"lr": 0.001}, log_dir=tmp_path, restart=True)

